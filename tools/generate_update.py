#!/usr/bin/env python3
"""Generate version and self-contained management page from tracked sources."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def write_if_changed(path,text):
    if not path.exists() or path.read_text()!=text:path.write_text(text)

def main():
    config=json.loads((ROOT/'version.json').read_text())
    version=config['software_version'];label=config['version']
    if not isinstance(version,int) or not 0<version<2**32:raise ValueError('software_version')
    import re
    if not re.fullmatch(r'[A-Za-z0-9.-]{1,31}',label):raise ValueError('version')
    if not config['catalog_url'].startswith('https://'):raise ValueError('catalog_url')
    source=ROOT/'firmware/matter/src'
    write_if_changed(source/'matter-app-device/Version.h','#pragma once\n#define CK_SOFTWARE_VERSION '+str(version)+'\n#define CK_VERSION_STRING '+json.dumps(label)+'\n')
    page=(source/'update/update.html').read_text().replace('{{CATALOG_URL}}',json.dumps(config['catalog_url'])).replace('{{SCRIPT}}',(source/'update/update.js').read_text())
    write_if_changed(source/'update/update_page.h','/* Generated by tools/generate_update.py. */\nstatic const char ck_update_page[] = '+json.dumps(page,ensure_ascii=False)+';\n')
if __name__=='__main__':main()
